/*
 * Regenerates src/lib/migrations/pendingMigrations.generated.ts from the
 * repo-root migration_*.sql files listed below.
 *
 * Why this exists: the Docker image ships only `dist/` and `public/` (see
 * Dockerfile), NOT the root migration_*.sql files. The boot-time migration
 * runner (src/lib/autoMigrate.ts) therefore cannot read those files at
 * runtime, so their contents are embedded into a committed .ts module that is
 * compiled into `dist/`. Run this whenever the listed SQL files change:
 *
 *   npx tsx src/scripts/gen_embedded_migrations.ts
 */
import fs from 'fs';
import path from 'path';

// The pending CRM migrations, in the order they must be applied.
const FILES = [
  'migration_makes_brands.sql',
  'migration_lead_ref_and_type.sql',
  'migration_expense_lead_deal_links.sql',
  'migration_expense_links_clarification.sql',
  'migration_form_ref_no.sql',
  'migration_account_location.sql',
  'migration_activity_type_check.sql',
  'migration_user_roles.sql',
];

const root = process.cwd();
const outPath = path.join(root, 'src/lib/migrations/pendingMigrations.generated.ts');

let out = `/* AUTO-GENERATED by src/scripts/gen_embedded_migrations.ts — DO NOT EDIT BY HAND.
   Embedded copies of the pending CRM migrations, in apply order. The source
   migration_*.sql files live at the repo root and are NOT shipped in the Docker
   image, so their contents are embedded here to run at boot (see lib/autoMigrate).
   Regenerate: npx tsx src/scripts/gen_embedded_migrations.ts */

export interface EmbeddedMigration { name: string; sql: string; }

export const PENDING_MIGRATIONS: EmbeddedMigration[] = [
`;

for (const f of FILES) {
  const sql = fs.readFileSync(path.join(root, f), 'utf8');
  out += `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(sql)} },\n`;
}
out += `];\n`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${FILES.length} migrations, ${out.length} bytes)`);
